import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const url = process.env.VOXEL_URL ?? 'http://127.0.0.1:4321';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--use-angle=swiftshader'] });
await mkdir('figures-out', { recursive: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'warning' && /context|WebGL/i.test(m.text()) && !/software WebGL|ReadPixels/i.test(m.text())) errors.push(m.text()); });
await page.goto(`${url}/lab/voxel-scene/?seed=7`);
await page.locator('.lab-main canvas[data-ready="1"]').waitFor();
assert.equal(await page.locator('.lab-main canvas').getAttribute('data-renderer'), 'webgl');
await page.locator('.lab-main').screenshot({ path: 'figures-out/voxel-world-desktop.png' });
const original = await page.locator('.lab-main canvas').screenshot();
await page.getByRole('button', { name: 'Rotate right', exact: true }).click();
assert(!original.equals(await page.locator('.lab-main canvas').screenshot()), 'rotation must redraw under reduced motion');
for (const biome of ['woodland', 'mushroom', 'snow', 'volcanic', 'oasis', 'village']) {
  await page.getByRole('combobox', { name: 'Generate a biome' }).selectOption(biome);
  await page.waitForFunction(b => document.querySelector('.lab-variant')?.textContent === `${b} island` && document.querySelector('.lab-main canvas')?.getAttribute('data-ready') === '1', biome);
  await page.locator('.lab-main').screenshot({ path: `figures-out/voxel-world-${biome}.png` });
  assert(!await page.locator('canvas[data-error]').count(), `${biome}: renderer error ${JSON.stringify(await page.locator('canvas[data-error]').evaluateAll(cs => cs.map(c => c.getAttribute('data-error'))))}`);
}
await page.getByRole('button', { name: 'roll', exact: true }).click();
await page.locator('.lab-main canvas[data-ready="1"]').waitFor();
const seed = new URL(page.url()).searchParams.get('seed');
assert(seed !== null);
const label = await page.locator('.lab-variant').textContent();
await page.getByRole('button', {name:'reset view',exact:true}).click();
await page.mouse.move(0,0);
await page.evaluate(() => window.scrollTo(0, document.querySelector('.lab-main').getBoundingClientRect().top + window.scrollY - 100));
const beforeReload = await page.locator('.lab-main canvas').screenshot({path:'figures-out/voxel-seed-before.png'});
await page.reload();
await page.locator('.lab-main canvas[data-ready="1"]').waitFor();
assert.equal(await page.locator('.lab-variant').textContent(), label, 'shared seed must restore the biome');
await page.mouse.move(0,0);
await page.evaluate(() => window.scrollTo(0, document.querySelector('.lab-main').getBoundingClientRect().top + window.scrollY - 100));
assert(beforeReload.equals(await page.locator('.lab-main canvas').screenshot({path:'figures-out/voxel-seed-after.png'})), 'shared seed must restore exactly the same 3D scene');
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('.lab-main').screenshot({ path: 'figures-out/voxel-world-phone.png' });
assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'phone layout overflow');
assert.deepEqual(errors, []);
await browser.close();
const fallbackBrowser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--disable-webgl'] });
const fallback = await fallbackBrowser.newPage({ viewport: { width: 900, height: 800 }, reducedMotion: 'reduce' });
await fallback.goto(`${url}/lab/voxel-scene/?seed=7`);
await fallback.locator('.lab-main canvas[data-ready="1"]').waitFor();
assert.equal(await fallback.locator('.lab-main canvas').getAttribute('data-renderer'), '2d-fallback');
assert.equal(await fallback.locator('canvas[data-error]').count(), 0);
await fallback.locator('.lab-main').screenshot({ path: 'figures-out/voxel-world-fallback.png' });
await fallbackBrowser.close();
console.log('Passed: all biome controls, rotation with reduced motion, exact scene restoration, phone layout, context lifecycle, WebGL fallback.');
