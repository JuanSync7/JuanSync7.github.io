// The translator's index as a file an agent can read: src/blueprints/INDEX.md, one row per named
// size of every blueprint (part, measure, token, where it is defined, what it resolves to, who
// else uses it). Built from the specs and the code by src/blueprints/catalogue.ts.
//   npm run blueprint:index            write it
//   npm run blueprint:index -- --check fail if it is out of date (inside npm run check)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ALL } from '../../src/blueprints/index.ts';
import { catalogue, MEASURE_WORDS } from '../../src/blueprints/catalogue.ts';

const ROOT = new URL('../..', import.meta.url).pathname;
const OUT = join(ROOT, 'src/blueprints/INDEX.md');
function walk(dir, test, out = {}) {
  for (const f of readdirSync(join(ROOT, dir))) {
    const p = join(dir, f);
    if (statSync(join(ROOT, p)).isDirectory()) walk(p, test, out);
    else if (test(p)) out[p] = readFileSync(join(ROOT, p), 'utf8');
  }
  return out;
}
const tokens = walk('src/styles/tokens', (p) => p.endsWith('.css'));
const sources = {
  ...walk('src/components', (p) => /\.(css|astro|tsx)$/.test(p)),
  ...walk('src/styles', (p) => p.endsWith('.css') && !p.includes('/tokens/')),
  ...walk('src/layouts', (p) => p.endsWith('.astro')),
  ...walk('src/pages', (p) => p.endsWith('.astro')),
};
const rows = catalogue(ALL, tokens, sources);
const cell = (s) => String(s).replace(/\|/g, '\\|');
const lines = [
  '# Blueprint index',
  '',
  'Generated by `npm run blueprint:index` from the specs in this folder; do not edit by hand.',
  'Every named size of every blueprint. To act on a request, find its row by blueprint, part (number,',
  'name or alias) and size; change the token where it is defined (a component token, never a scale',
  'step); check "Also changes" first. No row, or more than one: ask which part was meant.',
  '',
];
for (const b of ALL) {
  lines.push(`## ${b.title} (\`${b.id}\`, ${b.number} rev ${b.revision})`, '', b.summary, '');
  lines.push(
    '| Part | Also called | Size | Token | Defined at | Resolves to | Also changes |',
    '|---|---|---|---|---|---|---|',
  );
  for (const r of rows.filter((x) => x.blueprint === b.id)) {
    lines.push(
      `| ${r.part} ${cell(r.partName)} | ${cell(r.aliases.join(', ') || '-')} | ${MEASURE_WORDS[r.measure]} | \`${r.token}\` | ${r.defined} | ${cell(r.chain.join(' → '))} | ${cell([...r.sharedWith, r.readBy.length > 1 ? `read in ${r.readBy.length} files` : ''].filter(Boolean).join(', ') || '-')} |`,
    );
  }
  lines.push('');
}
const text = lines.join('\n');

// Coverage (R-BP-1): every shared component, chrome piece and layout has a blueprint, wraps one,
// or is named here with the reason it has none.
const WITHOUT = {
  'FigureCanvas.tsx': "its size is its host's; what it shows is a figure, drawn by the figure skill",
  'FigurePlate.tsx': "its size is its host's; what it shows is a baked figure, whose size and anchors are its manifest's",
  'HardwareIcon.tsx': 'a static icon; its geometry is in figures/kit/hardware and the icon playbook',
  'SlideIcon.tsx': 'a static icon; its geometry is in figures/kit/slides and the slide-icons playbook',
  'Monogram.astro': 'an SVG mark: its geometry is the drawing',
  'MarginNote.astro': 'drawn only in the gutter of a 2000 px page; not measured at 1280 or 390',
  'NightNav.astro': 'wraps PaperNav (paper-nav)',
  'NightFooter.astro': 'wraps PaperFooter (paper-footer)',
  'NightPage.astro': 'wraps PaperLayout (the page templates)',
  'PaperLayout.astro': 'the page chrome; measured through every page template',
  'PageTurn.astro': 'two fixed, empty layers the page turn moves during a swap; they have no layout to measure',
  'NightLayout.astro': 'the figure bench only (/figures), not a public page',
  'Layout.astro': 'legacy',
  'page-curl.ts': 'the page-swap motion script for every public page; it lays nothing out',
  'island-unmount.ts': 'holds a React island\'s unmount until it has hydrated, for PaperLayout; it lays nothing out',
  'site-search.ts': 'the search\'s keys and loading; it lays nothing out (the field is part 11 of paper-nav)',
  'search-results.ts': 'builds the search\'s result rows inside the sheet, which opens only on demand; it lays nothing out',
};
const LEGACY = [
  'CubeSwapDemo',
  'ZoomSwapDemo',
  'KineticWord',
  'LofiFooterFade',
  'NebulaStars',
  'NeonText',
  'NotGateDivider',
  'Placeholder',
  'PurpleSkyTransition',
  'SegmentedBar',
  'StarfieldStage',
  'StrikeThrough',
]; // the design system's legacy gallery
const covered = ALL.flatMap((b) => b.source.map((f) => f.split('/').pop()));
const shared = [
  ...readdirSync(join(ROOT, 'src/components/ui')).filter((f) => /\.(astro|tsx)$/.test(f)),
  ...readdirSync(join(ROOT, 'src/components/layout')),
  ...readdirSync(join(ROOT, 'src/layouts')),
];
const missing = shared.filter((f) => !covered.includes(f) && !WITHOUT[f] && !LEGACY.includes(f.replace(/\.\w+$/, '')));
// The renderers draw from measurements alone (R-BP-4): no component's selector in them.
const RENDERERS = ['drawing.ts', 'overlay.ts', 'sheet.ts', 'view.ts', 'measure.ts', 'sizing.ts', 'dom.ts'];
const named = RENDERERS.filter((f) =>
  /['"`]\.(?!bp-)[a-z][\w-]*/.test(readFileSync(join(ROOT, 'src/blueprints', f), 'utf8')),
);

if (process.argv.includes('--check')) {
  const same = readFileSync(OUT, 'utf8') === text;
  console.log(
    same ? 'blueprint index is up to date' : `${relative(ROOT, OUT)} is out of date: run npm run blueprint:index`,
  );
  for (const f of missing)
    console.error(`no blueprint for ${f}: write one, or name it with its reason in scripts/blueprints/index.mjs`);
  for (const f of named)
    console.error(`src/blueprints/${f} names a component's selector: the drawing must come from the spec`);
  process.exit(same && !missing.length && !named.length ? 0 : 1);
}
writeFileSync(OUT, text);
console.log(`wrote ${relative(ROOT, OUT)}: ${rows.length} sizes in ${ALL.length} blueprints`);
