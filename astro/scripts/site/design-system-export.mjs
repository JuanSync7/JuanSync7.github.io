#!/usr/bin/env node
// Writes the site's design system as one Markdown note, generated from the sources that define it
// (tokens/paper.css, tokens/typography.css, the component ledger in pages/design-system.astro, the
// layouts and the checks in package.json), so a copy kept elsewhere (the experience vault) is
// refreshed by running this, never edited by hand.
// Usage: node scripts/site/design-system-export.mjs [out.md]   (default: stdout)
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(new URL('../..', import.meta.url).pathname);
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const paper = read('src/styles/tokens/paper.css');
const rootBlock = paper.match(/:root \{([\s\S]*?)\n\}/)?.[1] ?? '';
const tokens = [...rootBlock.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--pp-[\w-]+):\s*([^;]+);/g)].map(([, n, v]) => [n, v.trim().replace(/\s+/g, ' ')]);
const night = [...(paper.match(/:root\[data-theme='dark'\] \{([\s\S]*?)\n\}/)?.[1] ?? '').matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(([, n, v]) => [n, v.trim()]);
const group = (re) => tokens.filter(([n]) => re.test(n));
const pair = (v) => v.match(/^light-dark\(\s*([^,]+?)\s*,\s*(.+?)\s*\)$/);
const colours = tokens.filter(([, v]) => pair(v) || /^#|^rgb|^color-mix/.test(v));
const ledger = [...read('src/pages/design-system.astro').matchAll(/<h3>(\w+)<\/h3><span class="ds-badge">([^<]*)<\/span><\/div><p>([^<]*)/g)];
const layouts = readdirSync(join(ROOT, 'src/layouts')).filter((f) => f.endsWith('.astro'));
const pkg = JSON.parse(read('package.json'));
const checks = ['check', 'figures:audit', 'site:tokens', 'site:reach', 'presentation:check', 'map:check', 'posts:check'].filter((k) => pkg.scripts[k]);
const commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
const row = (cells) => `| ${cells.join(' | ')} |`;
const out = [];
out.push('---', 'type: knowledge', 'schema: knowledge/1', 'topics:', '  - Design system', '  - Frontend design', 'domain:', '  - Web & frontend',
  'tags:', '  - type/knowledge', '  - domain/web-frontend', `generated_from: JuanSync7/JuanSync7.github.io@${commit}`, '---', '');
out.push('# Design system of juansync.dev (generated)', '');
out.push('> [!note] How to read this note', `> Generated by \`astro/scripts/site/design-system-export.mjs\` from the site repo at commit \`${commit}\`.`,
  '> Do not edit it here: change the tokens or the ledger in the repo and run the script again. The live page is',
  '> https://juansync.dev/design-system/. The taste behind it is [[Notes/Me/Knowledge/Frontend design]]; the rules for',
  '> using it are the decks [[Notes/Decks/Colour and contrast]], [[Notes/Decks/Page layout]] and',
  '> [[Notes/Decks/Designing and judging pages]].', '');
out.push('## The system in one paragraph', '',
  'Every public page is a notepad (`PaperLayout.astro`): a cream sheet by day and a gunmetal sheet by night, with the same',
  'punched strip, orange margin line and torn-paper hero. One signal orange marks the one thing to look at; everything',
  'else is ink on paper. Cards are transparent and divided by hairlines. Type is Manrope for reading, JetBrains Mono for',
  'labels and code comments, Caveat for the hand-written voice. Drawings are figures (`<FigureCanvas id>`), drawn in the',
  'night palette and recoloured to the page by a colour matrix fitted from these tokens at build time.', '');
out.push('## Colour', '', 'Each themed colour is one `light-dark(day, night)` token; the page picks the side through `color-scheme`',
  '(the visitor setting, or the theme button through `data-theme`).', '', row(['Token', 'Day', 'Night']), row(['---', '---', '---']));
for (const [n, v] of colours) { const p = pair(v); out.push(row([`\`${n}\``, `\`${p ? p[1] : v}\``, `\`${p ? p[2] : v}\``])); }
out.push('', 'Night-only values that are not colours:', '', ...night.map(([n, v]) => `- \`${n}: ${v}\``), '');
for (const [title, re] of [['Type', /^--pp-(sans|mono|hand|fs|w-|lh|tracking)/], ['Space, size and layout', /^--pp-(space|measure|pad|edge|radius|doc|note|line|hole|margin|col|wrap)/], ['Motion', /^--pp-(dur|ease|flip)/]]) {
  const g = group(re);
  if (!g.length) continue;
  out.push(`## ${title}`, '', row(['Token', 'Value']), row(['---', '---']), ...g.map(([n, v]) => row([`\`${n}\``, `\`${v.replace(/\|/g, '\\|')}\``])), '');
}
out.push('## Components (the ledger)', '', 'A shared component exists when it is rendered in section 06 of the design-system page.', '',
  row(['Component', 'Kind', 'What it is']), row(['---', '---', '---']), ...ledger.map(([, n, k, d]) => row([n, k, d.replace(/\|/g, '/').trim()])), '');
out.push('## Layouts', '', ...layouts.map((l) => `- \`src/layouts/${l}\``), '');
out.push('## Checks that hold it', '', ...checks.map((k) => `- \`npm run ${k}\`: \`${pkg.scripts[k].slice(0, 140)}\``), '');
const md = out.join('\n') + '\n';
if (process.argv[2]) writeFileSync(process.argv[2], md);
else process.stdout.write(md);
