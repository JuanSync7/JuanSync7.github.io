import type { Sketch, V3 } from './monoline';

/** The door end of the left wall: a lab coat on a rail of hooks, a pedal bin under it. */

const turnX = -Math.PI / 2;

/** A lab coat on a rail of hooks, and a pedal bin under it. */
export function coat(k: Sketch): void {
  k.object('coat', () => {
    k.box(0, 1.86, 2.48, 0.025, 1.9, 2.96);
    for (const z of [2.58, 2.72, 2.86])
      k.tube(
        [
          [0.024, 1.88, z],
          [0.07, 1.87, z],
          [0.085, 1.905, z],
        ],
        0.006,
      );
    const body: [number, number][] = [[0, 1.82], [0.06, 1.86], [0.2, 1.8], [0.25, 1.7], [0.27, 1.16], [0.21, 1.15], [0.22, 0.98], [-0.22, 0.98], [-0.21, 1.15], [-0.27, 1.16], [-0.25, 1.7], [-0.2, 1.8], [-0.06, 1.86]]; // prettier-ignore
    k.at([0.11, 0, 2.72], turnX, () => k.slab(body, 0, 0.07));
    const on = (pts: [number, number][]): void =>
      k.line(
        pts.map(([z, y]): V3 => [0.111, y, 2.72 + z]),
        'soft',
      );
    on([
      [-0.06, 1.86],
      [0, 1.6],
      [0.06, 1.86],
    ]);
    on([
      [0, 1.6],
      [0, 0.98],
    ]);
    on([
      [0.205, 1.16],
      [0.2, 1.68],
    ]);
    on([
      [-0.205, 1.16],
      [-0.2, 1.68],
    ]);
    on([
      [0.07, 1.3],
      [0.16, 1.3],
      [0.16, 1.18],
      [0.07, 1.18],
      [0.07, 1.3],
    ]);
    on([
      [-0.07, 1.3],
      [-0.16, 1.3],
      [-0.16, 1.18],
      [-0.07, 1.18],
      [-0.07, 1.3],
    ]);
    on([
      [-0.15, 1.62],
      [-0.08, 1.62],
    ]);
    for (const y of [1.52, 1.38, 1.24, 1.1]) k.circle([0.111, y, 2.745], 0.006, 'x', 'soft', 10);
  });
  k.object('bin', () => {
    k.lathe(0.36, 0, 2.66, [
      [0, 0],
      [0.13, 0],
      [0.15, 0.4],
      [0.155, 0.41],
      [0, 0.41],
    ]);
    k.lathe(0.36, 0.41, 2.66, [
      [0, 0],
      [0.158, 0],
      [0.15, 0.04],
      [0, 0.05],
    ]);
    k.box(0.48, 0, 2.62, 0.56, 0.03, 2.7);
  });
}
